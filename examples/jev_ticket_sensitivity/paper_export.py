"""Export tables/figures for the TypeSafe ticket-sensitivity paper.

Reads metrics from examples/jev_ticket_sensitivity/output/{live,synthetic}/
(generated by run.py; gitignored) and writes CSV/JSON/PNG under
papers/typesafe-ticket/{data,figures}/.

Usage (from repo root):

    uv run python examples/jev_ticket_sensitivity/run.py
    # optional, needs TYPESAFE_API_KEY + TYPESAFE_MODEL:
    uv run python examples/jev_ticket_sensitivity/run.py --live
    uv run python examples/jev_ticket_sensitivity/compare_surrogate_rules.py
    uv run python examples/jev_ticket_sensitivity/paper_export.py
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[2]
EXAMPLE = Path(__file__).resolve().parent
OUT_LIVE = EXAMPLE / "output" / "live"
OUT_SYN = EXAMPLE / "output" / "synthetic"
PAPER = ROOT / "papers" / "typesafe-ticket"
DATA = PAPER / "data"
FIGS = PAPER / "figures"

CENTER = {"amount": 250.0, "wait_hours": 8.0}


def _load(path: Path) -> dict:
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Run examples/jev_ticket_sensitivity/run.py "
            "(and optionally --live) first."
        )
    return json.loads(path.read_text())


def _node_rows(doc: dict, *, source: str) -> list[dict]:
    rows: list[dict] = []
    for node in doc.get("nodes") or []:
        theta = node.get("theta") or {}
        metrics = {m["name"].split(":")[0]: m for m in (node.get("metrics") or [])}
        # fisher_diagonal has param suffix — collect separately
        amount_diag = wait_diag = None
        ident_status = None
        for m in node.get("metrics") or []:
            name = m["name"]
            if name.startswith("fisher_diagonal:") and name.endswith(":amount"):
                amount_diag = m.get("value")
            elif name.startswith("fisher_diagonal:") and name.endswith(":wait_hours"):
                wait_diag = m.get("value")
            elif name.startswith("fisher_identifiability:"):
                ident_status = m.get("status")
        geom = node.get("geometry") or {}
        jac = geom.get("jacobian") or {}
        fish = geom.get("fisher") or {}
        F = np.asarray(fish.get("values") or [], dtype=float)
        trace = float(np.trace(F)) if F.size else None
        entropy = None
        for m in node.get("metrics") or []:
            if m["name"].startswith("entropy:"):
                entropy = m.get("value")
                break
        rows.append(
            {
                "source": source,
                "node": node["node_id"],
                "amount": theta.get("amount"),
                "wait_hours": theta.get("wait_hours"),
                "entropy_nats": entropy,
                "fisher_trace": fish.get("values") and float(np.trace(F)),
                "fisher_diag_amount": amount_diag,
                "fisher_diag_wait_hours": wait_diag,
                "jacobian_status": jac.get("status"),
                "fisher_status": fish.get("status"),
                "identifiability": ident_status,
                "run_id": doc.get("run_id"),
            }
        )
    return rows


def _capability_rows(doc: dict, *, source: str) -> list[dict]:
    caps = doc.get("capability_matrix") or {}
    entries = caps.get("entries") if isinstance(caps, dict) else caps
    rows = []
    for e in entries or []:
        rows.append(
            {
                "source": source,
                "capability": e.get("capability") or e.get("name"),
                "status": e.get("status"),
                "reason": e.get("reason_code") or e.get("reason"),
                "analysis_object": e.get("analysis_object"),
            }
        )
    return rows


def _write_csv(path: Path, rows: list[dict]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("")
        return
    with path.open("w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def _center_rows(rows: list[dict]) -> list[dict]:
    return [
        r
        for r in rows
        if r.get("amount") == CENTER["amount"] and r.get("wait_hours") == CENTER["wait_hours"]
    ]


def fig_entropy_bar(live_center: list[dict], syn_center: list[dict]) -> None:
    nodes = ["request_type", "needs_escalation", "impact"]
    live = {r["node"]: r["entropy_nats"] for r in live_center}
    syn = {r["node"]: r["entropy_nats"] for r in syn_center}
    x = np.arange(len(nodes))
    w = 0.35
    fig, ax = plt.subplots(figsize=(6.2, 3.6))
    ax.bar(x - w / 2, [syn.get(n) or 0 for n in nodes], w, label="offline synthetic")
    ax.bar(x + w / 2, [live.get(n) or 0 for n in nodes], w, label="TypeSafe live")
    ax.set_xticks(x)
    ax.set_xticklabels(["request_type", "needs_escalation", "impact"])
    ax.set_ylabel("Entropy (nats)")
    ax.set_title(r"Node entropy at $(amount, wait)=(250, 8)$")
    ax.legend()
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIGS / "entropy_center.pdf")
    fig.savefig(FIGS / "entropy_center.png", dpi=160)
    plt.close(fig)


def fig_fisher_diag(live_center: list[dict]) -> None:
    nodes = ["request_type", "needs_escalation", "impact"]
    by = {r["node"]: r for r in live_center}
    amount = [by[n]["fisher_diag_amount"] for n in nodes]
    wait = [by[n]["fisher_diag_wait_hours"] for n in nodes]
    x = np.arange(len(nodes))
    w = 0.35
    fig, ax = plt.subplots(figsize=(6.2, 3.6))
    ax.bar(x - w / 2, amount, w, label=r"$I_{ii}$ amount")
    ax.bar(x + w / 2, wait, w, label=r"$I_{ii}$ wait_hours")
    ax.set_xticks(x)
    ax.set_xticklabels(nodes)
    ax.set_ylabel("Fisher diagonal (nats)")
    ax.set_title("Live Fisher diagonals after step shrink (ok geometry)")
    ax.set_yscale("log")
    ax.legend()
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIGS / "fisher_diag_live.pdf")
    fig.savefig(FIGS / "fisher_diag_live.png", dpi=160)
    plt.close(fig)


def fig_synth_grid(syn_rows: list[dict]) -> None:
    nodes = ["request_type", "needs_escalation", "impact"]
    fig, axes = plt.subplots(1, 3, figsize=(10.5, 3.4), sharey=False)
    for ax, node in zip(axes, nodes):
        sub = [r for r in syn_rows if r["node"] == node]
        amounts = sorted({r["amount"] for r in sub})
        waits = sorted({r["wait_hours"] for r in sub})
        grid = np.full((len(waits), len(amounts)), np.nan)
        for r in sub:
            i = waits.index(r["wait_hours"])
            j = amounts.index(r["amount"])
            grid[i, j] = r["fisher_trace"]
        im = ax.imshow(grid, origin="lower", aspect="auto", cmap="viridis")
        ax.set_xticks(range(len(amounts)))
        ax.set_xticklabels([f"{a:g}" for a in amounts])
        ax.set_yticks(range(len(waits)))
        ax.set_yticklabels([f"{w:g}" for w in waits])
        ax.set_xlabel("amount")
        ax.set_ylabel("wait_hours")
        ax.set_title(f"{node}\ntr(I)")
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.suptitle("Offline synthetic Fisher trace on the 3×3 design grid")
    fig.tight_layout()
    fig.savefig(FIGS / "synth_fisher_grid.pdf")
    fig.savefig(FIGS / "synth_fisher_grid.png", dpi=160)
    plt.close(fig)


def fig_stability_before_after() -> None:
    """Documented before/after from the stencil shrink (PR #3)."""
    # Status only — unstable Fisher values are diagnostics, not validated.
    labels = ["request_type", "needs_escalation", "impact"]
    before = ["unstable"] * 3
    after = ["ok"] * 3
    fig, ax = plt.subplots(figsize=(6.0, 2.8))
    y = np.arange(len(labels))
    colors_b = ["#c44e52"] * 3
    colors_a = ["#55a868"] * 3
    ax.barh(y + 0.2, [1, 1, 1], 0.35, color=colors_b, label="before: step_stability_exceeded")
    ax.barh(y - 0.2, [1, 1, 1], 0.35, color=colors_a, label="after: ok (h_amt=0.25, h_wait=0.05, single-scale)")
    ax.set_yticks(y)
    ax.set_yticklabels(labels)
    ax.set_xticks([])
    ax.set_xlim(0, 1.6)
    ax.set_title("Live node geometry status: before vs after stencil shrink")
    ax.legend(loc="lower right", fontsize=8)
    for i, (b, a) in enumerate(zip(before, after)):
        ax.text(1.05, i + 0.2, b, va="center", fontsize=8, color="#c44e52")
        ax.text(1.05, i - 0.2, a, va="center", fontsize=8, color="#2a7a3a")
    fig.tight_layout()
    fig.savefig(FIGS / "stability_before_after.pdf")
    fig.savefig(FIGS / "stability_before_after.png", dpi=160)
    plt.close(fig)


RULE_ORDER = ("near_identity", "baseline", "stricter", "coarse_binary")
GRID_CSV = DATA / "surrogate_rule_loss_grid.csv"


def _load_surrogate_grid(path: Path = GRID_CSV) -> list[dict]:
    if not path.exists():
        raise FileNotFoundError(
            f"Missing {path}. Run examples/jev_ticket_sensitivity/compare_surrogate_rules.py first."
        )
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def _surrogate_center_rows(rows: list[dict]) -> list[dict]:
    return [
        row
        for row in rows
        if float(row["amount"]) == CENTER["amount"]
        and float(row["wait_hours"]) == CENTER["wait_hours"]
    ]


def fig_surrogate_rule_center_bar(center_rows: list[dict]) -> None:
    by_rule = {row["rule"]: row for row in center_rows}
    losses = [float(by_rule[name]["tr_loss"]) for name in RULE_ORDER]
    fig, ax = plt.subplots(figsize=(6.2, 3.6))
    ax.bar(range(len(RULE_ORDER)), losses, color=["#4c72b0", "#55a868", "#c44e52", "#8172b3"])
    ax.set_xticks(range(len(RULE_ORDER)))
    ax.set_xticklabels(list(RULE_ORDER), rotation=15, ha="right")
    ax.set_ylabel(r"$\mathrm{tr}(I_Z - I_A)$")
    ax.set_title(r"Surrogate rule information loss at $(250, 8)$")
    ax.grid(axis="y", alpha=0.3)
    fig.tight_layout()
    fig.savefig(FIGS / "surrogate_rule_loss_center.pdf")
    fig.savefig(FIGS / "surrogate_rule_loss_center.png", dpi=160)
    plt.close(fig)


def fig_surrogate_rule_loss_heatmap(rows: list[dict]) -> None:
    rules = [name for name in RULE_ORDER if name != "near_identity"]
    amounts = sorted({float(row["amount"]) for row in rows})
    waits = sorted({float(row["wait_hours"]) for row in rows})
    fig, axes = plt.subplots(1, len(rules), figsize=(11.5, 3.4), sharey=True)
    for ax, rule in zip(axes, rules):
        grid = np.full((len(waits), len(amounts)), np.nan)
        for row in rows:
            if row["rule"] != rule or row["status"] != "ok":
                continue
            i = waits.index(float(row["wait_hours"]))
            j = amounts.index(float(row["amount"]))
            grid[i, j] = float(row["tr_loss"])
        im = ax.imshow(grid, origin="lower", aspect="auto", cmap="magma")
        ax.set_xticks(range(len(amounts)))
        ax.set_xticklabels([f"{value:g}" for value in amounts])
        ax.set_yticks(range(len(waits)))
        ax.set_yticklabels([f"{value:g}" for value in waits])
        ax.set_xlabel("amount")
        if rule == rules[0]:
            ax.set_ylabel("wait_hours")
        ax.set_title(rule)
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)
    fig.suptitle(r"Surrogate $\mathrm{tr}(I_Z-I_A)$ on the 3×3 grid")
    fig.tight_layout()
    fig.savefig(FIGS / "surrogate_rule_loss_heatmap.pdf")
    fig.savefig(FIGS / "surrogate_rule_loss_heatmap.png", dpi=160)
    plt.close(fig)


def export_surrogate_rule_figures() -> dict:
    import sys

    sys.path.insert(0, str(EXAMPLE))
    from ticket_system import LOGIT_SCALE, PROB_FLOOR

    rows = _load_surrogate_grid()
    center_rows = _surrogate_center_rows(rows)
    fig_surrogate_rule_center_bar(center_rows)
    fig_surrogate_rule_loss_heatmap(rows)
    by_rule = {row["rule"]: row for row in center_rows}
    order_losses = [float(by_rule[name]["tr_loss"]) for name in RULE_ORDER]
    order_holds = all(
        order_losses[index] <= order_losses[index + 1] + 1e-12
        for index in range(len(order_losses) - 1)
    )
    ok_points = {
        (float(row["amount"]), float(row["wait_hours"]))
        for row in rows
        if row["status"] == "ok"
    }
    all_points = {(float(row["amount"]), float(row["wait_hours"])) for row in rows}

    mass_path = DATA / "surrogate_action_masses.csv"
    mass_rows = list(csv.DictReader(mass_path.open(newline="", encoding="utf-8")))
    probe_points = [(250.0, 8.0), (600.0, 2.0), (600.0, 8.0)]

    def _masses(amount: float, wait: float, rule: str) -> dict[str, float]:
        return {
            row["action"]: float(row["mass"])
            for row in mass_rows
            if float(row["amount"]) == amount
            and float(row["wait_hours"]) == wait
            and row["rule"] == rule
        }

    action_mass_points: dict[str, dict] = {}
    legacy_flip_present = False
    for amount, wait in probe_points:
        baseline = _masses(amount, wait, "baseline")
        stricter = _masses(amount, wait, "stricter")
        delta_priority = stricter.get("priority_queue", 0.0) - baseline.get("priority_queue", 0.0)
        delta_standard = stricter.get("standard_queue", 0.0) - baseline.get("standard_queue", 0.0)
        legacy = delta_priority > 1e-6 and delta_standard < -1e-6
        legacy_flip_present = legacy_flip_present or legacy
        action_mass_points[f"({amount:g},{wait:g})"] = {
            "priority_queue_delta": delta_priority,
            "standard_queue_delta": delta_standard,
            "legacy_flip_present": legacy,
        }

    summary = {
        "center": CENTER,
        "LOGIT_SCALE": float(LOGIT_SCALE),
        "PROB_FLOOR": float(PROB_FLOOR),
        "rule_order": list(RULE_ORDER),
        "tr_Iz": float(by_rule["near_identity"]["tr_Iz"]),
        "center_tr_Iz": float(by_rule["near_identity"]["tr_Iz"]),
        "tr_loss": {name: float(by_rule[name]["tr_loss"]) for name in RULE_ORDER},
        "center_losses": {
            name: {
                "tr_Iz": float(by_rule[name]["tr_Iz"]),
                "tr_Ia": float(by_rule[name]["tr_Ia"]),
                "tr_loss": float(by_rule[name]["tr_loss"]),
                "status": by_rule[name]["status"],
            }
            for name in RULE_ORDER
        },
        "center_order_holds": order_holds,
        "grid_ok_points": len(ok_points),
        "grid_points": len(all_points),
        "action_mass_points": action_mass_points,
        "legacy_flip_present": legacy_flip_present,
        "source_csv": str(GRID_CSV.relative_to(ROOT)),
        "action_mass_csv": str(mass_path.relative_to(ROOT)),
        "figures": [
            "figures/surrogate_rule_loss_center.pdf",
            "figures/surrogate_rule_loss_heatmap.pdf",
        ],
    }
    (DATA / "surrogate_rule_center_summary.json").write_text(
        json.dumps(summary, indent=2) + "\n"
    )
    return summary



def main() -> int:
    DATA.mkdir(parents=True, exist_ok=True)
    FIGS.mkdir(parents=True, exist_ok=True)

    live_doc = _load(OUT_LIVE / "metrics.json")
    syn_doc = _load(OUT_SYN / "metrics.json")

    live_rows = _node_rows(live_doc, source="live")
    syn_rows = _node_rows(syn_doc, source="synthetic")
    all_rows = live_rows + syn_rows
    _write_csv(DATA / "node_metrics.csv", all_rows)

    live_center = _center_rows(live_rows)
    syn_center = _center_rows(syn_rows)
    _write_csv(DATA / "center_comparison.csv", live_center + syn_center)

    caps = _capability_rows(live_doc, source="live") + _capability_rows(
        syn_doc, source="synthetic"
    )
    _write_csv(DATA / "capability_matrix.csv", caps)

    summary = {
        "live_run_id": live_doc.get("run_id"),
        "live_created_utc": live_doc.get("created_utc"),
        "synthetic_run_id": syn_doc.get("run_id"),
        "center": CENTER,
        "live_steps": {"amount": 0.25, "wait_hours": 0.05},
        "live_stencil": "single-scale step_scales=[1.0]",
        "offline_stencil": "two-scale step_scales=[1.0, 0.5]",
        "live_center_nodes": live_center,
        "synthetic_center_nodes": syn_center,
        "notes": [
            "System / action Fisher unsupported (no joint model; deterministic policy).",
            "needs_escalation and impact remain rank-deficient (not_identifiable) after step shrink.",
            "Before/after stability refers to PR #3 stencil change; unstable Fisher values are not validated.",
        ],
    }
    (DATA / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")

    # Stability narrative table (status only)
    stab = [
        {
            "node": n,
            "before_status": "unstable",
            "before_reason": "step_stability_exceeded",
            "after_status": "ok",
            "after_reason": "",
            "amount_step_before": 1.0,
            "wait_step_before": 0.25,
            "amount_step_after": 0.25,
            "wait_step_after": 0.05,
            "live_stencil_after": "single-scale",
        }
        for n in ("request_type", "needs_escalation", "impact")
    ]
    _write_csv(DATA / "stability_before_after.csv", stab)

    fig_entropy_bar(live_center, syn_center)
    fig_fisher_diag(live_center)
    fig_synth_grid(syn_rows)
    fig_stability_before_after()
    surrogate_summary = export_surrogate_rule_figures()

    print("wrote", DATA)
    print("wrote", FIGS)
    print(
        "surrogate center tr(I_Z)=%.6g order_holds=%s ok=%s/%s"
        % (
            surrogate_summary["center_tr_Iz"],
            surrogate_summary["center_order_holds"],
            surrogate_summary["grid_ok_points"],
            surrogate_summary["grid_points"],
        )
    )
    for r in live_center:
        print(
            f"  live {r['node']:18s} H={r['entropy_nats']:.4f} "
            f"tr(I)={r['fisher_trace']:.4f} "
            f"I_amt={r['fisher_diag_amount']:.4g} I_wait={r['fisher_diag_wait_hours']:.4g} "
            f"fish={r['fisher_status']} ident={r['identifiability']}"
        )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
